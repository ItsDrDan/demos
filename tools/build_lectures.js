#!/usr/bin/env node
/* Builds data/lectures.js (Dr. Dan's own lecture videos) from the Study Hub catalog.
   Source: ../games/data/hub.js (repo ItsDrDan/games, cloned next to this one).
   Each video keeps its title, length, chapter moments, and every course chapter that lists it.
   Usage: node tools/build_lectures.js            (rewrites data/lectures.js)
   The file it writes is a snapshot, so this repo works on its own after a build. */
const fs = require('fs'), path = require('path');
const hubFile = path.join(__dirname, '..', '..', 'games', 'data', 'hub.js');
if (!fs.existsSync(hubFile)) { console.error('Missing ' + hubFile + ' (clone ItsDrDan/games next to this repo).'); process.exit(1); }
global.window = {};
require(hubFile);
const H = window.HUB_DATA;
const where = {}; // id -> [{c, ch}]
for (const c of H.courses) for (const ch of c.chapters) for (const id of ch.videos || []) {
  (where[id] = where[id] || []).push([c.id, String(ch.id)]);
}
const out = [];
for (const v of H.videos) {
  const at = where[v.id] || [];
  const courses = [...new Set(at.map(a => a[0]))];
  const ch = {};
  for (const [c, n] of at) (ch[c] = ch[c] || []).includes(n) || ch[c].push(n);
  out.push({
    id: 'yt-' + v.id, type: 'lecture', yt: v.id, title: v.title.replace(/\s+/g, ' ').trim(),
    dur: v.duration || 0, courses, ch,
    moments: (v.moments || []).slice().sort((a, b) => a[0] - b[0]),
    src: 'Dr. Dan, YouTube @itsdrdan (Study Hub catalog, games/data/hub.js)'
  });
}
// chapter names, so the page can label filters without loading the hub
const chapters = {};
for (const c of H.courses) chapters[c.id] = c.chapters.map(ch => [String(ch.id), ch.label, ch.title]);
const body = '/* Generated by tools/build_lectures.js from games/data/hub.js (' + H.updated + '). Do not edit by hand. */\n' +
  'window.DEMO_CHAPTERS = ' + JSON.stringify(chapters) + ';\n' +
  'window.DEMO_LECTURES = [\n' + out.map(o => JSON.stringify(o)).join(',\n') + '\n];\n';
fs.writeFileSync(path.join(__dirname, '..', 'data', 'lectures.js'), body);
console.log('lectures:', out.length, '· in no chapter:', out.filter(o => !o.courses.length).length);
